"""
bench_multitool.py — The boundary-mutation battery applied to six scanners
over every credential type that five of them declare in a rule table and
that can be generated from a single regular expression.

WHY THIS EXPERIMENT
  bench_threetool_expanded.py compares three scanners. Three is too few to
  tell a defect of one implementation from a convention of the field, and
  its neutral comparisons rest on one third-party generator per pair. This
  harness adds three widely used open-source scanners:
    NP  Nosey Parker v0.24.0   (Rust; 183 rules, 162 in its default
                                ruleset; independent rule table)
    KF  Kingfisher v2.11.1     (Rust; 488 rules: 461 imported from
                                Betterleaks, a fork of Gitleaks, 26 from
                                Google's Veles, 1 of its own)
    DS  detect-secrets 1.5.0   (Python; 27 plugins, no rule table)

FIVE GENERATORS
  Credential types are drawn from five rule tables: GL, TH and AP exactly as
  in bench_threetool_expanded.py, plus NP and KF from their built-in rules.
  detect-secrets declares its formats in plugin code rather than in a table
  of regular expressions, so it is a scanner here, not a generator; a
  comparison can only favour a tool whose table generated the types, so a
  tool that generates none is never favoured.
  Generic rules (Gitleaks generic-api-key, Nosey Parker np.generic.*) name no
  provider, can never be label-matched, and are no longer generators: the
  three-tool harness counted GL:generic-api-key among its 774 types.

SHARED LINEAGE
  Kingfisher's table is mostly Gitleaks' rules by way of Betterleaks, so
  KF-generated types are no neutral ground for a comparison involving
  Gitleaks, nor GL-generated types for one involving Kingfisher. Each pair
  of tools is compared on the types generated by every table outside both
  tools' lineages ("neutral" in the output).

THE SAME CREDENTIAL TYPE MORE THAN ONCE
  ghp_ tokens are declared by four tables, so four types here share one
  provider and are not independent observations. Every type carries its
  provider (`provider` in per_type), and analysis_multitool.py reports
  comparisons with provider clusters as the unit alongside the type-level
  ones.

SCANNER SETTINGS THAT WOULD HAVE BIASED THE ORACLE
  Nosey Parker's report prints at most three matches per finding and three
  provenance entries per match by default; on a 2000-file probe that is 300
  of 2000 files. Kingfisher deduplicates identical secrets across files by
  default, so a value detected in one context hides the same value in every
  other. Both defaults are switched off (--max-matches=0
  --max-provenance=0 --suppress-redundant=false; --no-dedup).
  Verification, which sends a candidate secret to its provider's API, is
  disabled for every tool: --no-verification (TruffleHog), --no-validate
  (Kingfisher), --no-verify (detect-secrets, which otherwise verifies by
  default); Gitleaks and Nosey Parker do not verify. Update checks are off. TruffleHog is
  run TRUFFLEHOG_RUNS times and only detections present in every run are
  kept, as in bench_realworld_multilang.py.

Everything else -- contexts, the expected-rule oracle, paired retention,
encoding families, the hyphen marginal -- is bench_threetool_expanded.py's.

Seeded (20260823).
Run: python bench_multitool.py > results/multitool_bench.json
"""
