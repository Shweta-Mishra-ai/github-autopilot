"""
bench_threetool_expanded.py — The boundary-mutation battery applied to all
three scanners over every credential type any of them declares that can be
generated from a single regular expression.

WHY THIS EXPERIMENT
  The paper compares the three scanners on ten shared credential types and
  shows (paired_stats.py) that ten types cannot support a ranking: even a
  perfect 4/0 split has p = 0.125. Its own Future Work names the remedy --
  more credential TYPES, not more samples. This harness supplies them.

THREE GENERATORS, NOT ONE
  A corpus generated from one tool's rules favours that tool: every type in
  it is, by construction, a shape that tool declares. So credential types are
  drawn from all three tools' own rule tables:
    GL  Gitleaks 8.21.2 config/gitleaks.toml (same sampling and filters as
        bench_gitleaks_fulltable.py)
    TH  TruffleHog 3.82.13 detectors whose FromData uses exactly one
        regular expression: a backtick literal, or PrefixRegex(keywords) +
        literal. Detectors that need two or more patterns (an id and a
        secret, say) cannot be exercised by one embedded value and are
        excluded and counted, not silently dropped.
    AP  the primary subject at 38b2013, the same 24 rules as bench_mutation.py
  Every type is run through all three tools. Section "neutral" of the output
  compares each pair of tools only on types generated by the THIRD tool,
  which favours neither.

EXPECTED RULE
  As in bench_crosstool.py: per tool and type, the expected rule is the most
  frequent non-fallback rule the tool fires in the canonical context, and a
  type counts as covered by that tool when that rule fires on >= 50% of
  canonical samples.

PAIRED RETENTION
  Each sample value is embedded in every context, so for each tool we also
  report, of the samples that tool detected canonically, the fraction it
  still detects in each context. Value-level filters (TruffleHog's word-list
  filter, Gitleaks' entropy and stopwords) then cancel out, and what remains
  is the effect of the context alone.

Seeded (20260823).
Run: python bench_threetool_expanded.py > results/threetool_expanded_bench.json
"""
