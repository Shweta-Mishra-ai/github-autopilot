# Go POSIX classes, which Python's re does not support.
_POSIX = {
    "alnum": "A-Za-z0-9", "alpha": "A-Za-z", "digit": "0-9",
    "xdigit": "0-9A-Fa-f", "upper": "A-Z", "lower": "a-z",
    "word": "A-Za-z0-9_", "space": " \\t",
}


def _go_to_python(p):
    p = re.sub(r"\[:(\w+):\]", lambda m: _POSIX.get(m.group(1), m.group(0)), p)
    return gl._to_python(p)


# ── credential-type extraction ──────────────────────────────────────────────
def types_gitleaks(cfg):
    out = []
    for rule in cfg["rules"]:
        if "path" in rule:
            continue
        kpat = gl.keyword_pattern(rule)
        try:
            spat = gl.secret_pattern(rule)
            kre = re.compile(kpat) if kpat else None
        except (re.error, ValueError):
            continue
        filt = gl.Filters(cfg, rule)
        out.append({
            "id": f"GL:{rule['id']}", "secret": spat, "kw_pattern": kpat,
            "kw_regex": kre, "accepts": filt.accepts})
    return out


_TH_PAT = re.compile(r"(\w+)\s*=\s*regexp\.MustCompile\((.*?)\)\s*\n")
_TH_KW = re.compile(r"func \(s Scanner\) Keywords\(\) \[\]string \{\s*return \[\]string\{([^}]*)\}")


def types_trufflehog(src):
    out, skipped = [], Counter()
    root = os.path.join(src, "pkg", "detectors")
    for f in sorted(glob.glob(os.path.join(root, "**", "*.go"), recursive=True)):
        if f.endswith("_test.go"):
            continue
        s = open(f).read()
        if "func (s Scanner) FromData" not in s:
            continue
        name = os.path.relpath(os.path.dirname(f), root)
        pats = _TH_PAT.findall(s)
        if len(pats) != 1:
            skipped["needs_multiple_patterns" if pats else "no_pattern"] += 1
            continue
        expr = pats[0][1].strip()
        m_lit = re.fullmatch(r"`([^`]*)`", expr)
        m_pre = re.fullmatch(
            r'detectors\.PrefixRegex\(\[\]string\{([^}]*)\}\)\s*\+\s*`([^`]*)`', expr)
        kws = re.findall(r'"([^"]*)"', (_TH_KW.search(s) or [None, ""])[1])
        if m_lit:
            body, prefix_kws = m_lit.group(1), None
        elif m_pre:
            prefix_kws = re.findall(r'"([^"]*)"', m_pre.group(1))
            body = m_pre.group(2)
        else:
            skipped["pattern_built_by_helper"] += 1
            continue
        span = gl._first_capture(body)
        sec = body[span[0] + 1:span[1] - 1] if span else body
        if sec.startswith("?P<"):
            sec = sec[sec.index(">") + 1:]
        kw_pattern = None
        if prefix_kws:
            ok = [k for k in prefix_kws if re.fullmatch(r"[A-Za-z0-9_.-]+", k)]
            if not ok:
                skipped["keyword_not_identifier"] += 1
                continue
            kw_pattern = re.escape(ok[0])
        try:
            spat = _go_to_python(sec)
            re.compile(spat, re.ASCII)
        except re.error:
            skipped["pattern_not_translatable"] += 1
            continue
        low = [k.lower() for k in kws]

        def accepts(secret, line, low=low):
            return not low or any(k in line.lower() for k in low)
        out.append({
            "id": f"TH:{name}", "secret": spat, "kw_pattern": kw_pattern,
            "kw_regex": re.compile(kw_pattern) if kw_pattern else None,
            "accepts": accepts})
    return out, dict(skipped)


def types_autopilot():
    out = []
    for name, pat, _sev, *_ in PATTERNS:
        if name in AP_STRUCTURAL or name in AP_KEYWORD_ANCHORED:
            continue
        core = re.sub(r"^\\b", "", pat)
        core = re.sub(r"\\b$", "", core)
        out.append({
            "id": f"AP:{name}", "secret": gl._to_python(core), "kw_pattern": None,
            "kw_regex": None, "accepts": lambda s, line: True})
    return out


# ── corpus ──────────────────────────────────────────────────────────────────
def sample(t):
    sre = re.compile(t["secret"], re.ASCII)
    got, draws = [], 0
    while len(got) < N_SAMPLES and draws < MAX_DRAWS:
        draws += 1
        try:
            v = exrex.getone(t["secret"], limit=40)
        except Exception:
            return [], sre
        if t["kw_pattern"]:
            k = exrex.getone(t["kw_pattern"], limit=4)
            if not re.fullmatch(r"[A-Za-z0-9_.-]+", k):
                continue
            k = f"{k}_value"
        else:
            k = "cfg_value"
        if not (gl._printable_ascii(v) and sre.fullmatch(v)):
            continue
        if t["accepts"](v, gl.PREFIX_CONTEXTS["canonical"](k, v)):
            got.append((k, v))
    return got, sre


def build(types, workdir):
    meta, info, idx = {}, {}, 0
    for t in types:
        samples, sre = sample(t)
        stratum = "keyword" if t["kw_pattern"] else "prefix"
        rec = {"stratum": stratum, "n_valid_samples": len(samples)}
        info[t["id"]] = rec
        if len(samples) < N_SAMPLES:
            rec["excluded"] = f"only {len(samples)} valid samples in {MAX_DRAWS} draws"
            continue
        base = gl.KEYWORD_CONTEXTS if t["kw_pattern"] else gl.PREFIX_CONTEXTS
        contexts = {**base, **gl.EXTENSION_CONTEXTS[stratum]}
        applicable = [m for m, ch in gl.FINAL_CHAR.items() if all(
            sre.fullmatch(v[:-1] + ch) and t["accepts"](
                v[:-1] + ch, gl.PREFIX_CONTEXTS["canonical"](k, v[:-1] + ch))
            for k, v in samples)]
        rec["final_char_applicable"] = applicable
        for i, (k, v) in enumerate(samples):
            lines = {ctx: fn(k, v) for ctx, fn in contexts.items()}
            for m in applicable:
                lines[m] = base["canonical"](k, v[:-1] + gl.FINAL_CHAR[m])
            for ctx, line in lines.items():
                idx += 1
                sid = f"s{idx:07d}"
                with open(os.path.join(workdir, f"{sid}.txt"), "w") as fh:
                    fh.write(line + "\n")
                meta[sid] = (t["id"], ctx, i)
    return meta, info


# ── scanners ────────────────────────────────────────────────────────────────
_SID = re.compile(r"(s\d{7})\.txt")


def scan_autopilot(workdir, meta):
    out, t0 = {}, time.perf_counter()
    for sid in meta:
        line = open(os.path.join(workdir, f"{sid}.txt")).read().rstrip("\n")
        out[sid] = {f.pattern_name for f in scan_diff("+" + line + "\n",
                                                       file_path="app/settings.py")}
    return out, time.perf_counter() - t0


def scan_gitleaks(workdir, meta):
    rep = os.path.join(os.path.dirname(workdir), "_gl.json")
    t0 = time.perf_counter()
    subprocess.run([gl.GITLEAKS, "detect", "--source", workdir, "--no-git",
                    "--config", gl.GITLEAKS_TOML, "--report-format", "json",
                    "--report-path", rep, "--no-banner", "--log-level", "error"],
                   capture_output=True, timeout=7200)
    el = time.perf_counter() - t0
    out = {sid: set() for sid in meta}
    for f in json.load(open(rep)) or []:
        m = _SID.match(os.path.basename(f.get("File", "")))
        if m and m.group(1) in out:
            out[m.group(1)].add(f.get("RuleID", "?"))
    return out, el


def scan_trufflehog(workdir, meta):
    t0 = time.perf_counter()
    p = subprocess.run([TRUFFLEHOG, "filesystem", workdir, "--json",
                        "--no-verification", "--no-update"],
                       capture_output=True, timeout=14400, text=True)
    el = time.perf_counter() - t0
    out = {sid: set() for sid in meta}
    for line in p.stdout.splitlines():
        try:
            rec = json.loads(line)
        except ValueError:
            continue
        if "DetectorName" not in rec:
            continue
        fp = rec.get("SourceMetadata", {}).get("Data", {}).get("Filesystem", {}).get("file", "")
        m = _SID.match(os.path.basename(fp))
        if m and m.group(1) in out:
            out[m.group(1)].add(rec["DetectorName"])
    return out, el


# ── analysis ────────────────────────────────────────────────────────────────
def analyse_tool(tool, meta, findings, types):
    fb = FALLBACK[tool]
    by_type = defaultdict(list)
    for sid, (tid, ctx, i) in meta.items():
        by_type[tid].append((sid, ctx, i))
    per = {}
    for tid, rows in by_type.items():
        canon = [s for s, c, _ in rows if c == "canonical"]
        counts = Counter(r for s in canon for r in findings[s] - fb)
        exp = counts.most_common(1)[0][0] if counts else None
        canon_rate = sum(1 for s in canon if exp in findings[s]) / len(canon) if exp else 0.0
        rec = {"expected_rule": exp, "canonical_rule_ok": round(canon_rate, 4),
               "covered": canon_rate >= 0.5}
        if rec["covered"]:
            ok_canon = {i for s, c, i in rows if c == "canonical" and exp in findings[s]}
            ctx_rows = defaultdict(list)
            for s, c, i in rows:
                ctx_rows[c].append((s, i))
            cells = {}
            for c, rs in ctx_rows.items():
                n = len(rs)
                hit = sum(1 for s, _ in rs if exp in findings[s])
                missed = sum(1 for s, _ in rs if not findings[s])
                paired = [s for s, i in rs if i in ok_canon]
                cells[c] = {
                    "n": n,
                    "rule_ok": round(hit / n, 4),
                    "missed": round(missed / n, 4),
                    "paired_retention": round(
                        sum(1 for s in paired if exp in findings[s]) / len(paired), 4)
                    if paired else None,
                }
            rec["cells"] = cells
            rec["BR"] = min(v["rule_ok"] for k, v in cells.items() if k not in gl.NOT_IN_BR)
            rec["fragile_contexts"] = sorted(
                k for k, v in cells.items()
                if k not in gl.NOT_IN_BR and v["paired_retention"] is not None
                and v["paired_retention"] < 0.5)
        per[tid] = rec
    return per


# ── does the rule that fired name the same provider as the type? ────────────
# A type counts as covered only if the tool fires the same rule on most
# canonical samples, but that rule may belong to another provider: the
# subject's PagerDuty rule, for one, fires on any 32-character alphanumeric
# value. Such a detection carries the wrong label (and severity), so coverage
# is reported twice, and comparisons use the label-matched form.
_SAME_PROVIDER = [{"gcp", "google"}]


def _norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def provider_of_type(tid):
    src, name = tid.split(":", 1)
    if src == "GL":
        head = name.split("-")[0]
    elif src == "TH":
        head = name.split("/")[0]
    else:
        head = name.split()[0]
    return _norm(head)


def provider_of_rule(tool, rule):
    if tool == "gitleaks":
        return _norm(rule.split("-")[0])
    if tool == "autopilot":
        return _norm(rule.split()[0])
    return _norm(rule)


def label_matches(tid, tool, rule):
    """Same provider: equal, one a prefix of the other, or a shared prefix of
    at least five characters (TruffleHog's 'SplunkOberservabilityToken' for
    splunkobservabilitytoken; 'TeamworkSpaces' for teamworkcrm)."""
    a, b = provider_of_type(tid), provider_of_rule(tool, rule)
    if a == b or a.startswith(b) or b.startswith(a):
        return len(min(a, b, key=len)) >= 2 or a == b
    if len(os.path.commonprefix([a, b])) >= 5:
        return True
    return any(any(a.startswith(x) for x in g) and any(b.startswith(x) for x in g)
               for g in _SAME_PROVIDER)


def sign_test(a, b):
    """Exact two-sided binomial sign test on discordant pairs."""
    n = a + b
    if n == 0:
        return 1.0
    k = min(a, b)
    p = sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n
    return min(1.0, 2 * p)


def compare(per, type_ids, key="covered"):
    out = {}
    for x, y in (("autopilot", "gitleaks"), ("autopilot", "trufflehog"),
                 ("gitleaks", "trufflehog")):
        a = sum(1 for t in type_ids if per[x][t][key] and not per[y][t][key])
        b = sum(1 for t in type_ids if per[y][t][key] and not per[x][t][key])
        both = sum(1 for t in type_ids if per[x][t][key] and per[y][t][key])
        out[f"{x}_vs_{y}"] = {"n_types": len(type_ids), "both": both,
                              f"only_{x}": a, f"only_{y}": b, "p": sign_test(a, b)}
    return out


def context_summary(per_tool, type_ids):
    agg = defaultdict(lambda: {"types": 0, "total_failure": 0, "sum_ret": 0.0})
    for t in type_ids:
        rec = per_tool[t]
        if not rec["covered"]:
            continue
        for c, v in rec["cells"].items():
            if v["paired_retention"] is None:
                continue
            a = agg[c]
            a["types"] += 1
            a["sum_ret"] += v["paired_retention"]
            a["total_failure"] += v["paired_retention"] == 0.0
    return {c: {"types": a["types"], "total_failure": a["total_failure"],
                "mean_paired_retention": round(a["sum_ret"] / a["types"], 4)}
            for c, a in agg.items()}


def main():
    random.seed(SEED)
    cfg = tomllib.loads(open(gl.GITLEAKS_TOML, "rb").read().decode())
    th_types, th_skipped = types_trufflehog(TRUFFLEHOG_SRC)
    types = types_gitleaks(cfg) + th_types + types_autopilot()
    tmp = tempfile.mkdtemp(prefix="three_")
    wd = os.path.join(tmp, "corpus")
    os.mkdir(wd)
    try:
        meta, info = build(types, wd)
        f_ap, t_ap = scan_autopilot(wd, meta)
        f_gl, t_gl = scan_gitleaks(wd, meta)
        f_th, t_th = scan_trufflehog(wd, meta)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    tids = sorted({tid for tid, _, _ in meta.values()})
    per = {"autopilot": analyse_tool("autopilot", meta, f_ap, types),
           "gitleaks": analyse_tool("gitleaks", meta, f_gl, types),
           "trufflehog": analyse_tool("trufflehog", meta, f_th, types)}
    for tool in TOOLS:
        for t in tids:
            rec = per[tool][t]
            rec["label_matched"] = bool(rec["covered"] and
                                        label_matches(t, tool, rec["expected_rule"]))
    src = {g: [t for t in tids if t.startswith(g + ":")] for g in ("GL", "TH", "AP")}
    neutral = {"autopilot_vs_gitleaks": "TH", "autopilot_vs_trufflehog": "GL",
               "gitleaks_vs_trufflehog": "AP"}
    by_src = {g: compare(per, ids, "label_matched") for g, ids in src.items()}
    return {
        "design": __doc__.strip().splitlines()[0],
        "seed": SEED,
        "n_samples_per_cell": N_SAMPLES,
        "n_files": len(meta),
        "scan_wall_s": {"autopilot": round(t_ap, 2), "gitleaks": round(t_gl, 2),
                        "trufflehog": round(t_th, 2)},
        "types_generated": {g: len(ids) for g, ids in src.items()},
        "types_excluded": {t: v["excluded"] for t, v in info.items() if "excluded" in v},
        "trufflehog_detectors_not_single_pattern": th_skipped,
        "coverage": {tool: {g: sum(per[tool][t]["covered"] for t in ids)
                            for g, ids in src.items()} for tool in TOOLS},
        "coverage_label_matched": {tool: {g: sum(per[tool][t]["label_matched"] for t in ids)
                                          for g, ids in src.items()} for tool in TOOLS},
        "mislabelled_coverage_by_rule": {tool: dict(Counter(
            per[tool][t]["expected_rule"] for t in tids
            if per[tool][t]["covered"] and not per[tool][t]["label_matched"]).most_common())
            for tool in TOOLS},
        "paired_coverage_pooled_any_rule": compare(per, tids),
        "paired_coverage_pooled": compare(per, tids, "label_matched"),
        "paired_coverage_by_generator": by_src,
        "paired_coverage_neutral": {k: by_src[g][k] | {"generator": g}
                                    for k, g in neutral.items()},
        "context_summary": {tool: {g: context_summary(per[tool], ids)
                                   for g, ids in src.items()} for tool in TOOLS},
        "per_type": {t: {"stratum": info[t]["stratum"],
                         "final_char_applicable": info[t].get("final_char_applicable", []),
                         **{tool: per[tool][t] for tool in TOOLS}} for t in tids},
    }


if __name__ == "__main__":
    print(json.dumps(main(), indent=2))
